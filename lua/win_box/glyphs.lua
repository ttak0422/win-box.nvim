local M = {}

function M.render(label)
  local glyph = glyphs[label]
  if not glyph then return nil end
  local first, last, trim = 1, #glyph, math.huge
  while first <= last and not glyph[first]:find("%S") do first = first + 1 end
  while last >= first and not glyph[last]:find("%S") do last = last - 1 end
  if first > last then return nil end
  for i = first, last do
    if glyph[i]:find("%S") then trim = math.min(trim, #(glyph[i]:match("^ *"))) end
  end
  local rows, width = {}, 0
  for i = first, last do
    local line = glyph[i]:sub(trim + 1):gsub(" +$", "")
    rows[#rows + 1] = line
    width = math.max(width, vim.fn.strdisplaywidth(line))
  end
  return rows, width
end

return M
